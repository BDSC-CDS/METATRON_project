"""Run the LLM-as-judge evaluation with the selected model environment."""

import argparse
import importlib.util
import os
import subprocess
import sys
from pathlib import Path
import pandas as pd

import boto3
import instructor  # library for get reliable JSON from any LLM
from openai import OpenAI
from dotenv import load_dotenv

from utils_call_bedrock_models import cred_path


EVALUATION_DIR = Path(__file__).resolve().parent


def run_script(script_name: str, *args: object) -> None:
    """Run an evaluation stage, passing in-process arguments when provided."""
    if args:
        module_name = Path(script_name).stem.replace("-", "_")
        spec = importlib.util.spec_from_file_location(
            module_name, EVALUATION_DIR / script_name
        )
        if spec is None or spec.loader is None:
            raise ImportError(f"Unable to load evaluation script: {script_name}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        module.main(*args)
        return

    subprocess.run(
        [sys.executable, str(EVALUATION_DIR / script_name)],
        cwd=EVALUATION_DIR,
        check=True,
    )


def main(
    n_selected_cases: int,
    model_env: str,
    model_name: str,
    data_version: str,
    data_path: str,
) -> None:
    """Run the AWS session-token setup when needed, then the LLM judge."""
    if n_selected_cases < 1:
        raise ValueError("N_SELECTED_CASES must be greater than zero.")
    if not Path(data_path).is_absolute():
        raise ValueError("data_path must be a complete absolute path.")

    if model_env.lower() == "aws":
        run_script("00_session_token.py")

        # Load the temporary credentials generated by the MFA step.
        load_dotenv(str(EVALUATION_DIR / cred_path / "temporary_cred.env"))
        access_key_id = os.getenv("AWS_ACCESS_KEY_ID")
        access_secret_key = os.getenv("AWS_SECRET_ACCESS_KEY")
        session_token = os.getenv("AWS_SESSION_TOKEN")

        # Create the Bedrock client before starting the judge evaluation.
        bedrock_client = boto3.client(
            "bedrock-runtime",
            aws_access_key_id=access_key_id,
            aws_secret_access_key=access_secret_key,
            aws_session_token=session_token,
            region_name="us-west-2",
        )
        client = instructor.from_bedrock(bedrock_client)
    else:
        load_dotenv()
        llm_api_key = os.getenv("OPENAI_APIKEY")
        client = OpenAI(api_key=llm_api_key)

    approaches_df_complete = pd.read_csv(
        os.path.join(data_path, f"recommendation_comparison_{data_version}.csv"),
        sep=";",
    )
    approaches_df_complete.attrs["version"] = data_version

    run_script(
        "01_LLM_as_Judge.py",
        n_selected_cases,
        model_name,
        model_env,
        client,
        approaches_df_complete,
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run the LLM-as-judge evaluation."
    )
    parser.add_argument("--n-selected-cases", type=int, required=True)
    parser.add_argument(
        "--model-env",
        required=True,
        choices=["aws", "apikey"],
        help="Use AWS Bedrock (with MFA token setup) or an API-key GPT model.",
    )
    parser.add_argument("--model-name", required=True)
    parser.add_argument("--data-version", required=True)
    parser.add_argument(
        "--data-path",
        required=True,
        help="Complete absolute path to the recommendation data directory.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    main(**vars(parse_args()))
